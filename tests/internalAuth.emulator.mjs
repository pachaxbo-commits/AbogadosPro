await assert.rejects(updateDoc(caseRef(assistant.db, 'two'), { nombre: 'Alterado' }));
await adminDb.collection('workspaces').doc(workspace.uid).collection('tareas').doc('assigned-task').set({ casoId: 'two', titulo: 'Tarea asignada', ownerUserId: second.id, assignedUserIds: [helper.id] });
const taskRef = doc(assistant.db, 'workspaces', workspace.uid, 'tareas', 'assigned-task');
