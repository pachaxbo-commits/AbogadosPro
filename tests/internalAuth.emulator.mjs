await cases.doc('one').set({ nombre: 'Caso Uno', ownerUserId: first.id, assignedUserIds: [], assistantVisible: true });
await cases.doc('two').set({ nombre: 'Caso Dos', ownerUserId: second.id, assignedUserIds: [helper.id], assistantVisible: true });
await cases.doc('legacy').set({ nombre: 'Caso Antiguo', ownerUserId: first.id, assignedUserIds: [helper.id], honorariosAcordados: 500 });
await adminDb.collection('workspaces').doc(workspace.uid).collection('caseFinance').doc('two').set({ honorariosAcordados: 500, ownerUserId: second.id });
const caseRef = (db, id) => doc(db, 'workspaces', workspace.uid, 'casos', id);
assert.equal((await getDoc(caseRef(boss.db, 'one'))).exists(), true);
assert.equal((await getDoc(caseRef(lawyer1.db, 'one'))).exists(), true);
await assert.rejects(getDoc(caseRef(lawyer1.db, 'two')));
await assert.rejects(getDoc(caseRef(lawyer2.db, 'one')));
assert.equal((await getDoc(caseRef(assistant.db, 'two'))).exists(), true);
