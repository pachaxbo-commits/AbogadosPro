import assert from 'node:assert/strict';
import { initializeApp as initializeAdmin } from 'firebase-admin/app';
import { getAuth as getAdminAuth } from 'firebase-admin/auth';
import { getFirestore as getAdminFirestore } from 'firebase-admin/firestore';
import { initializeApp as initializeClient, deleteApp } from 'firebase/app';
import { getAuth, connectAuthEmulator, signInWithEmailAndPassword, signOut, updatePassword } from 'firebase/auth';
import { getFirestore, connectFirestoreEmulator, doc, getDoc, getDocs, setDoc, updateDoc, query, collection, where } from 'firebase/firestore';

process.env.FIREBASE_PROJECT_ID = 'demo-abogadospro';
process.env.INTERNAL_AUTH_RULES_READY = 'true';
const { default: handler } = await import('../api/internal.ts');
const adminApp = initializeAdmin({ projectId: 'demo-abogadospro' });
const adminAuth = getAdminAuth(adminApp);
const adminDb = getAdminFirestore(adminApp);
const authUrl = `http://${process.env.FIREBASE_AUTH_EMULATOR_HOST}`;
const [firestoreHost, firestorePort] = process.env.FIRESTORE_EMULATOR_HOST.split(':');
function client(name) {
  const app = initializeClient({ apiKey: 'demo-api-key', authDomain: 'demo-abogadospro.firebaseapp.com', projectId: 'demo-abogadospro', appId: 'demo-app' }, name);
  const auth = getAuth(app);
  connectAuthEmulator(auth, authUrl, { disableWarnings: true });
  const db = getFirestore(app);
  connectFirestoreEmulator(db, firestoreHost, Number(firestorePort));
  return { app, auth, db };
}
function call(action, studioToken, internalToken, data = {}) {
  return new Promise((resolve, reject) => {
    const req = { method: 'POST', headers: { authorization: `Bearer ${studioToken}`, ...(internalToken ? { 'x-internal-token': internalToken } : {}) }, body: { action, ...data } };
    const res = { code: 200, status(code) { this.code = code; return this; }, json(payload) { resolve({ status: this.code, ...payload }); return this; } };
    Promise.resolve(handler(req, res)).catch(reject);
  });
}
const studio = client('studio-test');
const boss = client('boss-test');
const lawyer1 = client('lawyer1-test');
const lawyer2 = client('lawyer2-test');
const assistant = client('assistant-test');
const workspace = await adminAuth.createUser({ email: 'studio@example.test', password: 'StudioPassword123!' });
await adminDb.collection('users').doc(workspace.uid).set({ uid: workspace.uid, role: 'user', workspaceId: workspace.uid });
await adminDb.collection('workspaces').doc(workspace.uid).set({ ownerUid: workspace.uid, name: 'Estudio ficticio' });
await signInWithEmailAndPassword(studio.auth, 'studio@example.test', 'StudioPassword123!');
const studioToken = await studio.auth.currentUser.getIdToken();
const boot = await call('bootstrap', studioToken, null, { displayName: 'Jefe de prueba', password: 'BossPassword123!' });
assert.equal(boot.status, 201, JSON.stringify(boot));
assert.equal(boot.user.role, 'abogado');
assert.equal(boot.user.isOfficeAdmin, true);
await assert.rejects(signInWithEmailAndPassword(boss.auth, boot.user.email, 'incorrecta'));
await signInWithEmailAndPassword(boss.auth, boot.user.email, 'BossPassword123!');
const bossToken = await boss.auth.currentUser.getIdToken();
assert.equal((await call('me', studioToken, bossToken)).user.id, boot.user.id);
const create = async (name, role, password) => {
  const result = await call('create', studioToken, bossToken, { displayName: name, role, password });
  assert.equal(result.status, 201, JSON.stringify(result));
  return result.user;
};
